-- Run as SYS (sysdba) in CDB$ROOT.
-- Creates the CONTROL test user: the same grant list as the restricted user PLUS the two
-- removed grants (SELECT ANY TABLE, LOCK ANY TABLE) restored. This is the known-good
-- baseline (tests C and C2). Grants below were dumped back out of the live test instance
-- (DBA_SYS_PRIVS / DBA_ROLE_PRIVS / DBA_TAB_PRIVS) to guarantee they match what was run.

WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE USER C##CONTROL IDENTIFIED BY control123 CONTAINER=ALL;

GRANT CREATE SESSION TO C##CONTROL CONTAINER=ALL;
GRANT SET CONTAINER TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$DATABASE TO C##CONTROL CONTAINER=ALL;
GRANT FLASHBACK ANY TABLE TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ANY TABLE TO C##CONTROL CONTAINER=ALL;     -- restored for the control
GRANT SELECT_CATALOG_ROLE TO C##CONTROL CONTAINER=ALL;
GRANT EXECUTE_CATALOG_ROLE TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ANY TRANSACTION TO C##CONTROL CONTAINER=ALL;
GRANT LOGMINING TO C##CONTROL CONTAINER=ALL;

GRANT CREATE TABLE TO C##CONTROL CONTAINER=ALL;
GRANT LOCK ANY TABLE TO C##CONTROL CONTAINER=ALL;       -- restored for the control
GRANT CREATE SEQUENCE TO C##CONTROL CONTAINER=ALL;
GRANT UNLIMITED TABLESPACE TO C##CONTROL CONTAINER=ALL;

GRANT EXECUTE ON DBMS_LOGMNR TO C##CONTROL CONTAINER=ALL;
GRANT EXECUTE ON DBMS_LOGMNR_D TO C##CONTROL CONTAINER=ALL;

GRANT SELECT ON V_$LOG TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$LOG_HISTORY TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$LOGMNR_LOGS TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$LOGMNR_CONTENTS TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$LOGMNR_PARAMETERS TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$LOGFILE TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$ARCHIVED_LOG TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$ARCHIVE_DEST_STATUS TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$TRANSACTION TO C##CONTROL CONTAINER=ALL;

GRANT SELECT ON V_$MYSTAT TO C##CONTROL CONTAINER=ALL;
GRANT SELECT ON V_$STATNAME TO C##CONTROL CONTAINER=ALL;

EXIT
