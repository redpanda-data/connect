package prometheus

import (
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestPrometheusPushErrorRedacted(t *testing.T) {
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.WriteHeader(http.StatusInternalServerError)
	}))
	defer server.Close()

	pushURL := strings.Replace(server.URL, "http://", "http://u:S3cretPass@", 1)
	p := promFromYAML(t, `
push_url: %v
`, pushURL)

	err := p.Close(t.Context())
	require.Error(t, err)
	assert.NotContains(t, err.Error(), "S3cretPass")
}
