package confluent

import (
	"encoding/json"
	"errors"
	"fmt"
	"slices"

	"github.com/redpanda-data/benthos/v4/public/schema"
)

// commonToJSONSchema converts a benthos common schema to a JSON Schema string.
func commonToJSONSchema(c schema.Common) (string, error) {
	m, err := commonToJSONSchemaNode(c)
	if err != nil {
		return "", err
	}
	b, err := json.Marshal(m)
	if err != nil {
		return "", fmt.Errorf("marshalling JSON Schema: %w", err)
	}
	return string(b), nil
}

// commonToJSONSchemaNode converts c to a JSON Schema node. Optional nodes also
// accept null, mirroring the ["null", T] union emitted for Avro.
func commonToJSONSchemaNode(c schema.Common) (map[string]any, error) {
	m, err := commonToJSONSchemaInner(c)
	if err != nil {
		return nil, err
	}
	if c.Optional {
		return jsonSchemaNullable(m), nil
	}
	return m, nil
}

// jsonSchemaNullable returns a node that accepts null in addition to whatever
// m accepts. It changes m in place and returns it, so callers must pass a map
// they own; every caller passes the new map from commonToJSONSchemaInner.
//
// A node with a single type gets a type array (["string", "null"]), which
// keeps type-specific keywords such as format and pattern in place. A union
// gets a {"type": "null"} branch added to its oneOf, rather than being wrapped
// in anyOf, so that a schema registry checking compatibility can still match
// the old branches one to one. Nodes that already accept null (any, null, and
// unions with a branch that accepts null) are returned unchanged.
func jsonSchemaNullable(m map[string]any) map[string]any {
	if jsonSchemaAcceptsNull(m) {
		return m
	}
	// m["type"] is the JSON Schema "type" keyword. commonToJSONSchemaInner sets
	// it to one string for every node except union ({"oneOf": ...}) and any
	// ({}), which have no "type" keyword.
	if t, ok := m["type"].(string); ok {
		m["type"] = []string{t, "null"}
		return m
	}
	if oneOf, ok := m["oneOf"].([]any); ok {
		m["oneOf"] = append(oneOf, map[string]any{"type": "null"})
		return m
	}
	return map[string]any{"anyOf": []any{m, map[string]any{"type": "null"}}}
}

// jsonSchemaAcceptsNull reports whether a node generated by
// commonToJSONSchemaInner already accepts null. A union must not get a second
// null branch: oneOf requires exactly one branch to match, so null would match
// two branches and be rejected.
func jsonSchemaAcceptsNull(m map[string]any) bool {
	if len(m) == 0 {
		return true
	}
	switch t := m["type"].(type) {
	case string:
		return t == "null"
	case []string:
		return slices.Contains(t, "null")
	}
	if oneOf, ok := m["oneOf"].([]any); ok {
		for _, b := range oneOf {
			if bm, ok := b.(map[string]any); ok && jsonSchemaAcceptsNull(bm) {
				return true
			}
		}
	}
	if anyOf, ok := m["anyOf"].([]any); ok {
		for _, b := range anyOf {
			if bm, ok := b.(map[string]any); ok && jsonSchemaAcceptsNull(bm) {
				return true
			}
		}
	}
	return false
}

func commonToJSONSchemaInner(c schema.Common) (map[string]any, error) {
	switch c.Type {
	case schema.Object:
		return commonToJSONSchemaObject(c)
	case schema.Int32, schema.Int64:
		return map[string]any{"type": "integer"}, nil
	case schema.Float32, schema.Float64:
		return map[string]any{"type": "number"}, nil
	case schema.Boolean:
		return map[string]any{"type": "boolean"}, nil
	case schema.String:
		return map[string]any{"type": "string"}, nil
	case schema.ByteArray:
		return map[string]any{"type": "string", "contentEncoding": "base64"}, nil
	case schema.Null:
		return map[string]any{"type": "null"}, nil
	case schema.Array:
		return commonToJSONSchemaArray(c)
	case schema.Map:
		return commonToJSONSchemaMap(c)
	case schema.Union:
		return commonToJSONSchemaUnion(c)
	case schema.Timestamp:
		return map[string]any{"type": "string", "format": "date-time"}, nil
	case schema.Date:
		return map[string]any{"type": "string", "format": "date"}, nil
	case schema.TimeOfDay:
		return map[string]any{"type": "string", "format": "time"}, nil
	case schema.UUID:
		return map[string]any{"type": "string", "format": "uuid"}, nil
	case schema.Decimal:
		if c.Logical == nil || c.Logical.Decimal == nil {
			return nil, fmt.Errorf("decimal field %q missing precision/scale", c.Name)
		}
		return map[string]any{
			"type":    "string",
			"pattern": decimalPattern(c.Logical.Decimal.Precision, c.Logical.Decimal.Scale),
		}, nil
	case schema.BigDecimal:
		return map[string]any{
			"type":    "string",
			"pattern": `^-?(0|[1-9][0-9]*)(\.[0-9]+)?$`,
		}, nil
	case schema.Any:
		return map[string]any{}, nil
	default:
		return nil, fmt.Errorf("unsupported schema type: %v", c.Type)
	}
}

func commonToJSONSchemaObject(c schema.Common) (map[string]any, error) {
	properties := make(map[string]any, len(c.Children))
	var required []string
	for _, child := range c.Children {
		childMap, err := commonToJSONSchemaNode(child)
		if err != nil {
			return nil, fmt.Errorf("property %q: %w", child.Name, err)
		}
		properties[child.Name] = childMap
		if !child.Optional {
			required = append(required, child.Name)
		}
	}
	m := map[string]any{
		"type":       "object",
		"properties": properties,
	}
	if len(required) > 0 {
		m["required"] = required
	}
	return m, nil
}

func commonToJSONSchemaArray(c schema.Common) (map[string]any, error) {
	if len(c.Children) == 0 {
		return nil, errors.New("array schema requires at least one child for items type")
	}
	items, err := commonToJSONSchemaNode(c.Children[0])
	if err != nil {
		return nil, fmt.Errorf("array items: %w", err)
	}
	return map[string]any{
		"type":  "array",
		"items": items,
	}, nil
}

func commonToJSONSchemaMap(c schema.Common) (map[string]any, error) {
	if len(c.Children) == 0 {
		return nil, errors.New("map schema requires at least one child for value type")
	}
	values, err := commonToJSONSchemaNode(c.Children[0])
	if err != nil {
		return nil, fmt.Errorf("map values: %w", err)
	}
	return map[string]any{
		"type":                 "object",
		"additionalProperties": values,
	}, nil
}

func commonToJSONSchemaUnion(c schema.Common) (map[string]any, error) {
	oneOf := make([]any, 0, len(c.Children))
	for i, child := range c.Children {
		childMap, err := commonToJSONSchemaNode(child)
		if err != nil {
			return nil, fmt.Errorf("union branch %d: %w", i, err)
		}
		oneOf = append(oneOf, childMap)
	}
	return map[string]any{"oneOf": oneOf}, nil
}

// decimalPattern returns a JSON Schema regex matching the canonical decimal
// string form for Decimal(p, s). The pattern enforces no leading zeros (except
// a single 0 before the decimal point), no scientific notation, optional
// leading minus, and exactly s fractional digits when s > 0.
func decimalPattern(precision, scale int32) string {
	m := precision - scale
	switch {
	case scale == 0:
		// Integer-only: up to precision digits.
		return fmt.Sprintf(`^-?(0|[1-9][0-9]{0,%d})$`, m-1)
	case m == 0:
		// Fractional-only (e.g. Decimal(4,4)): integer part can only be 0.
		return fmt.Sprintf(`^-?0\.[0-9]{%d}$`, scale)
	default:
		return fmt.Sprintf(`^-?(0|[1-9][0-9]{0,%d})\.[0-9]{%d}$`, m-1, scale)
	}
}
