// LobLocatorInfo contains the parsed information from a SELECT_LOB_LOCATOR redo entry.
// The LOB column type (CLOB/BLOB/NCLOB) is not parsed from the SQL here; callers
// should resolve it from the database schema (ALL_TAB_COLUMNS).
type LobLocatorInfo struct {
	Schema   string
	Table    string
	Column   string
	PKValues map[string]any
}

var (
	reLobColumn  = regexp.MustCompile(`(?i)select\s+"([^"]+)"\s+into`)
	reLobTable   = regexp.MustCompile(`(?i)from\s+"([^"]+)"\."([^"]+)"`)
	reLobWherePK = regexp.MustCompile(`"([^"]+)"\s*=\s*'((?:[^']|'')*)'`)
)

// ParseSelectLobLocator parses the PL/SQL DECLARE block generated by Oracle
// LogMiner for SELECT_LOB_LOCATOR (operation 9) entries. It returns the schema,
// table, column name, and the WHERE clause PK values that identify which row
// owns this LOB. The LOB type (CLOB/BLOB/NCLOB) is not parsed here — callers
// should look it up from the database schema instead.
func ParseSelectLobLocator(sql string) (*LobLocatorInfo, error) {
	colMatch := reLobColumn.FindStringSubmatch(sql)
	if colMatch == nil {
		return nil, errors.New("could not find column name in SELECT_LOB_LOCATOR SQL")
	}
	column := colMatch[1]

	tableMatch := reLobTable.FindStringSubmatch(sql)
	if tableMatch == nil {
		return nil, errors.New("could not find schema.table in SELECT_LOB_LOCATOR SQL")
	}
	schema := tableMatch[1]
	table := tableMatch[2]

	// Extract WHERE clause PK pairs, stopping before ROWID.
	pkValues := make(map[string]any)
	whereIdx := strings.Index(strings.ToLower(sql), " where ")
	if whereIdx >= 0 {
		whereClause := sql[whereIdx:]
		if rowidIdx := strings.Index(strings.ToLower(whereClause), "rowid"); rowidIdx >= 0 {
			whereClause = whereClause[:rowidIdx]
		}
		for _, m := range reLobWherePK.FindAllStringSubmatch(whereClause, -1) {
			pkValues[m[1]] = strings.ReplaceAll(m[2], "''", "'")
		}
	}

	return &LobLocatorInfo{
		Schema:   schema,
		Table:    table,
		Column:   column,
		PKValues: pkValues,
	}, nil
}

// LobWriteInfo contains the parsed information from a LOB_WRITE redo entry.
type LobWriteInfo struct {
	Data   []byte
	Offset int64
	Length int64
}

// ParseLobTrim extracts the new length N from a dbms_lob.trim(locator, N) call
// emitted by Oracle LogMiner for LOB_TRIM (op 11) entries.
func ParseLobTrim(sql string) (int64, error) {
	const keyword = "dbms_lob.trim"
	for from := 0; from < len(sql); {
		idx := indexFold(sql[from:], keyword)
		if idx < 0 {
			break
		}
		pos := from + idx + len(keyword)
		from = from + idx + 1

		// dbms_lob.trim\s*\(
		pos = skipSpace(sql, pos)
		if pos >= len(sql) || sql[pos] != '(' {
			continue
		}
		pos++
		// [^,]+,
		comma := strings.IndexByte(sql[pos:], ',')
		if comma < 1 {
			continue
		}
		pos += comma + 1
		digits, next, found := scanDigits(sql, skipSpace(sql, pos))
		if !found {
			continue
		}
		next = skipSpace(sql, next)
		if next >= len(sql) || sql[next] != ')' {
			continue
		}
		n, err := strconv.ParseInt(digits, 10, 64)
		if err != nil {
			return 0, fmt.Errorf("parsing LOB_TRIM length: %w", err)
		}
		return n, nil
	}
	return 0, errors.New("could not find dbms_lob.trim() call in LOB_TRIM SQL")
}

// ParseLobWrite parses the dbms_lob.write() call generated by Oracle LogMiner
// for LOB_WRITE (operation 10) entries. For CLOB and NCLOB (isBinary=false) the
// data is normally extracted as a plain string literal, but Oracle may also emit
// HEXTORAW() for CLOB/NCLOB in some cases (e.g. zero-padded or null-filled segments);
// for BLOB (isBinary=true) it is always hex-decoded from HEXTORAW().
//
// Expected format (PL/SQL variable with separate buffer assignment):
//
//	buf_c := 'Hello';
//	dbms_lob.write(loc_c, 5, 1, buf_c);
func ParseLobWrite(sql string, isBinary bool) (*LobWriteInfo, error) {
	length, offset, writeIdx, ok := parseLobWriteParams(sql)
	if !ok {
		return nil, errors.New("could not parse dbms_lob.write() call in LOB_WRITE SQL")
	}

	expr, hexData, isHex, structural, ok := findLobData(sql, writeIdx)
	if !ok {
		return nil, errors.New("could not find LOB data in LOB_WRITE SQL")
	}

	var data []byte
	var err error
	switch {
	case isBinary && !isHex:
		return nil, errors.New("could not find HEXTORAW() in LOB_WRITE BLOB data expression")
	case isBinary:
		if data, err = hex.DecodeString(hexData); err != nil {
			return nil, fmt.Errorf("hex-decoding BLOB data: %w", err)
		}
	case isHex:
		// Oracle sometimes emits HEXTORAW() for CLOB/NCLOB data (e.g. zero-padded segments).
		if data, err = hex.DecodeString(hexData); err != nil {
			return nil, fmt.Errorf("hex-decoding CLOB data: %w", err)
		}
	default:
		if structural {
			expr = resolveLiteralEscapes(expr, length)
		} else if strings.Contains(expr, "''") {
			expr = strings.ReplaceAll(expr, "''", "'")
		}
		data = []byte(expr)
	}
	return &LobWriteInfo{Data: data, Offset: offset, Length: length}, nil
}

// parseLobWriteParams extracts length and offset from the dbms_lob.write call,
// along with the index at which the call starts. The call follows the data
// buffer assignment, so the search runs from the end of the statement to avoid
// matching the same text inside LOB data.
func parseLobWriteParams(sql string) (length, offset int64, writeIdx int, ok bool) {
	const keyword = "dbms_lob.write"
	for end := len(sql); end > 0; {
		idx := lastIndexFold(sql[:end], keyword)
		if idx < 0 {
			return 0, 0, 0, false
		}
		end = idx
		pos := skipSpace(sql, idx+len(keyword))
		if pos >= len(sql) || sql[pos] != '(' {
			continue
		}
		pos++
		// First argument: [^,]+,
		comma := strings.IndexByte(sql[pos:], ',')
		if comma < 1 {
			continue
		}
		pos += comma + 1
		lenStr, next, found := scanDigits(sql, skipSpace(sql, pos))
		if !found {
			continue
		}
		next = skipSpace(sql, next)
		if next >= len(sql) || sql[next] != ',' {
			continue
		}
		offStr, next, found := scanDigits(sql, skipSpace(sql, next+1))
		if !found {
			continue
		}
		next = skipSpace(sql, next)
		if next >= len(sql) || sql[next] != ',' {
			continue
		}
		l, err := strconv.ParseInt(lenStr, 10, 64)
		if err != nil {
			return 0, 0, 0, false
		}
		o, err := strconv.ParseInt(offStr, 10, 64)
		if err != nil {
			return 0, 0, 0, false
		}
		return l, o, idx, true
	}
	return 0, 0, 0, false
}

// findLobData locates the LOB payload preceding the dbms_lob.write call that
// starts at writeIdx. The end of a string literal is found structurally (the
// quote right before the ";" that precedes the write call) rather than by
// scanning for quotes, because Oracle 11g does not escape single quotes inside
// the data, so the first lone quote is not a reliable terminator. When the
// statement does not have that shape it falls back to findLobAssignment, and
// structural is false.
func findLobData(sql string, writeIdx int) (literal, hexData string, isHex, structural, ok bool) {
	const (
		assign  = ":="
		hexOpen = "hextoraw('"
	)

	// Walk back from the write call over whitespace, the terminating ";" and
	// optional whitespace to the end of the value expression.
	end := trimSpaceBack(sql, writeIdx)
	if end > 0 && sql[end-1] == ';' {
		end = trimSpaceBack(sql, end-1)
		for from := 0; from < end; {
			idx := strings.Index(sql[from:end], assign)
			if idx < 0 {
				break
			}
			from += idx + len(assign)
			pos := skipSpace(sql, from)
			if pos >= end {
				break
			}
			if len(sql)-pos >= len(hexOpen) && strings.EqualFold(sql[pos:pos+len(hexOpen)], hexOpen) {
				start := pos + len(hexOpen)
				if end-2 >= start && sql[end-2:end] == "')" && isHexDigits(sql[start:end-2]) {
					return "", sql[start : end-2], true, true, true
				}
				continue
			}
			if sql[pos] != '\'' {
				continue
			}
			if start := pos + 1; end-1 >= start && sql[end-1] == '\'' {
				return sql[start : end-1], "", false, true, true
			}
			break
		}
	}

	literal, hexData, isHex, ok = findLobAssignment(sql)
	return literal, hexData, isHex, false, ok
}

// resolveLiteralEscapes decides whether the doubled quotes in a literal are
// escapes. Oracle 21c+ doubles single quotes inside the data while 11g emits
// them raw, so the declared dbms_lob.write length (the character count of the
// real data) is used to tell the two apart. If neither interpretation matches
// the length, the data is treated as escaped.
func resolveLiteralEscapes(raw string, declared int64) string {
	if !strings.Contains(raw, "''") {
		return raw
	}
	unescaped := strings.ReplaceAll(raw, "''", "'")
	if lengthMatches(unescaped, declared) || !lengthMatches(raw, declared) {
		return unescaped
	}
	return raw
}

// lengthMatches reports whether s has n characters, counting either runes or
// UTF-16 code units (CLOB/NCLOB lengths use the latter for non-BMP data).
func lengthMatches(s string, n int64) bool {
	runes := int64(utf8.RuneCountInString(s))
	if runes == n {
		return true
	}
	// UTF-16 units are never fewer than runes, and pure ASCII has no
	// surrogate pairs, so only scan when neither shortcut applies.
	if n < runes || int64(len(s)) == runes {
		return false
	}
	var supplementary int64
	for _, r := range s {
		if r >= 0x10000 {
			supplementary++
		}
	}
	return runes+supplementary == n
}

func trimSpaceBack(s string, end int) int {
	for end > 0 && isRegexSpace(s[end-1]) {
		end--
	}
	return end
}

// findLobAssignment locates the first ":=" assignment whose right-hand side is
// either HEXTORAW('<hex>') or a quoted string literal. For HEXTORAW it returns
// the hex digits with isHex set; for a literal it returns the raw content
// between the quotes (with ” escapes still in place).
func findLobAssignment(sql string) (literal, hexData string, isHex, ok bool) {
	const (
		assign   = ":="
		hexOpen  = "hextoraw('"
		hexClose = "')"
	)
	for from := 0; from < len(sql); {
		idx := strings.Index(sql[from:], assign)
		if idx < 0 {
			return "", "", false, false
		}
		from += idx + len(assign)
		pos := skipSpace(sql, from)
		if pos >= len(sql) {
			return "", "", false, false
		}

		if len(sql)-pos >= len(hexOpen) && strings.EqualFold(sql[pos:pos+len(hexOpen)], hexOpen) {
			start := pos + len(hexOpen)
			end := strings.IndexByte(sql[start:], '\'')
			if end < 0 || !strings.HasPrefix(sql[start+end:], hexClose) || !isHexDigits(sql[start:start+end]) {
				continue
			}
			return "", sql[start : start+end], true, true
		}

		if sql[pos] != '\'' {
			continue
		}
		start := pos + 1
		for i := start; ; {
			q := strings.IndexByte(sql[i:], '\'')
			if q < 0 {
				break
			}
			q += i
			if q+1 < len(sql) && sql[q+1] == '\'' {
				i = q + 2
				continue
			}
			return sql[start:q], "", false, true
		}
	}
	return "", "", false, false
}

func isHexDigits(s string) bool {
	for i := 0; i < len(s); i++ {
		c := s[i]
		if (c < '0' || c > '9') && (c < 'a' || c > 'f') && (c < 'A' || c > 'F') {
			return false
		}
	}
	return true
}

// isRegexSpace matches the regexp \s class (RE2 semantics).
func isRegexSpace(c byte) bool {
	return c == ' ' || c == '\t' || c == '\n' || c == '\f' || c == '\r'
}

func skipSpace(s string, pos int) int {
	for pos < len(s) && isRegexSpace(s[pos]) {
		pos++
	}
	return pos
}

func scanDigits(s string, pos int) (digits string, next int, found bool) {
	start := pos
	for pos < len(s) && s[pos] >= '0' && s[pos] <= '9' {
		pos++
	}
	return s[start:pos], pos, pos > start
}

// indexFold returns the index of the first ASCII case-insensitive occurrence
// of the lowercase keyword in s, or -1.
func indexFold(s, keyword string) int {
	n := len(keyword)
	first := keyword[0]
	for i := 0; i+n <= len(s); i++ {
		if c := s[i] | 0x20; c == first && strings.EqualFold(s[i:i+n], keyword) {
			return i
		}
	}
	return -1
}

// lastIndexFold is the reverse-scanning counterpart of indexFold.
func lastIndexFold(s, keyword string) int {
	n := len(keyword)
	first := keyword[0]
	for i := len(s) - n; i >= 0; i-- {
		if c := s[i] | 0x20; c == first && strings.EqualFold(s[i:i+n], keyword) {
			return i
		}
	}
	return -1
}
