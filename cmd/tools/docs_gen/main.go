// docs_gen writes the generated reference content under docs/modules, which
// is gitignored. Each release attaches it to the GitHub release as
// redpanda-connect-docs.tar.gz, and the docs site merges it with the pages in
// rp-connect-docs; see docs/README.md.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/redpanda-data/connect/v4/internal/plugins"
	"github.com/redpanda-data/connect/v4/public/schema"

	_ "github.com/redpanda-data/connect/v4/cmd/tools/docs_gen/allcomponents"
)

// repoSource names the origin of generated text when docs_gen cannot name
// the file that registers a component: the whole repository.
const repoSource = "the component specs in https://github.com/redpanda-data/connect"

// changeHint tells a reader how to change generated text. The generator runs
// in this repository even when the spec lives in benthos.
const changeHint = " To change it, edit the spec and run `task docs` in https://github.com/redpanda-data/connect."

// bannerFor opens every generated file. source is a noun phrase, such as
// "the component spec in redpanda-data/benthos@v4.84.0:internal/impl/pure/processor_mapping.go".
// The docs build reads "autogenerated from <source>." to report provenance in
// the Markdown twins, so the sentence shape is part of the contract.
func bannerFor(source string) string {
	return "// This content is autogenerated from " + source + ". Do not edit manually."
}

// componentSource names where a component's text comes from: the file that
// registers it when the registration scan found one, else the repository.
func componentSource(file string) string {
	if file == "" {
		return repoSource
	}
	return "the component spec in " + file
}

// bloblangSource is componentSource for a Bloblang function or method.
func bloblangSource(file string) string {
	if file == "" {
		return "the Bloblang specs in https://github.com/redpanda-data/connect"
	}
	return "the Bloblang spec in " + file
}

func generatedBannerFor(source string) string { return bannerFor(source) + changeHint }

func metadataBannerFor(source string) string {
	return bannerFor(source) + " Metadata fields come from the `== Metadata` section of the component description." + changeHint
}

func descBannerFor(source string) string {
	return bannerFor(source) + " The summary and description come from the component spec." + changeHint + "\n" +
		"//\n" +
		"// Pages consume this partial in two places so both stay fresh:\n" +
		"//   header: include::...[tag=meta]  (sets :description: for search snippets and meta tags)\n" +
		"//   body:   include::...[tag=body]   (renders the status notice, summary, and description)\n" +
		"// Pages with reference sections also include [tag=footnotes] where those sections belong."
}

func emptyMetadataPartialFor(source string) string {
	return bannerFor(source) + " The component description has no Metadata section, so this partial is empty.\n"
}

func emptyFieldsPartialFor(source string) string {
	return bannerFor(source) + " The component has no config fields, so this partial is empty.\n"
}

func emptyExamplesPartialFor(source string) string {
	return bannerFor(source) + " The component has no examples, so this partial is empty.\n"
}

func emptyDescriptionPartialFor(source string) string {
	return bannerFor(source) + " The component has no summary or description, so this partial is empty.\n" +
		"\n// tag::meta[]\n// end::meta[]\n\n// tag::body[]\n// end::body[]\n\n// tag::footnotes[]\n// end::footnotes[]\n"
}

// Repository-level banners, for files that aggregate many components.
var (
	bannerPrefix            = bannerFor(repoSource)
	generatedBanner         = generatedBannerFor(repoSource)
	emptyDescriptionPartial = emptyDescriptionPartialFor(repoSource)
)

// generatedDirs are the directories under the components module that this
// tool owns. They are emptied before every run so that a component removed
// from the code also disappears from the docs.
var generatedDirs = []string{
	"partials/fields",
	"partials/examples",
	"partials/metadata",
	"partials/descriptions",
	"partials/availability",
	"partials/platforms",
	"partials/bloblang",
	"partials/bloblang-functions",
	"partials/bloblang-methods",
	"examples/common",
	"examples/advanced",
}

func main() {
	root := "./docs/modules/components"
	flag.StringVar(&root, "dir", root, "The components module directory to write docs to")
	flag.Parse()

	raw, err := schema.Standard("", "").MarshalJSONV0()
	if err != nil {
		panic(err)
	}
	full, err := parseFullSchema(raw)
	if err != nil {
		panic(err)
	}

	// Platforms come first, so a failure leaves the committed docs in place.
	plat, err := loadPlatforms(full)
	if err != nil {
		panic(fmt.Errorf("finding the components that only cgo builds include: %w", err))
	}
	fmt.Printf("Components that only cgo builds include: %v\n", strings.Join(plat.cgoOnlyKeys(), ", "))
	if unsourced := plat.unsourcedKeys(); len(unsourced) > 0 {
		fmt.Printf("Components whose registering file docs_gen could not read, so their banners name the repository: %v\n", strings.Join(unsourced, ", "))
	}

	// Only a build with every component can tell which files are stale, and
	// only it can write the component catalog and the cgo-only list. Two build
	// constraints add components: x_benthos_extra adds zmq4 (which also needs
	// cgo and libzmq) and ffi (pure Go), and cgo adds tigerbeetle_cdc. A tagged
	// build can't compile without cgo, so builtWithAllComponents also implies
	// cgo. A partial build would delete the docs of the missing components, so
	// it keeps existing files instead.
	w := writer{root: root, platforms: plat}
	if builtWithAllComponents {
		// x_benthos_extra exists to add components, so a full build that finds
		// none means the standard build didn't run the way it should.
		if len(plat.cgoOnlyKeys()) == 0 {
			panic("found no cgo-only components in a build with x_benthos_extra; check that go list can list the standard build")
		}
		for _, d := range generatedDirs {
			if err := os.RemoveAll(filepath.Join(root, d)); err != nil {
				panic(err)
			}
		}
		w.platformFiles(full)
	} else {
		fmt.Fprintln(os.Stderr, "Built without x_benthos_extra: keeping existing files, so docs for removed components are not pruned, and keeping the existing component catalog and cgo-only list, which need every component. CI runs `CGO_ENABLED=1 TAGS=x_benthos_extra task docs`.")
	}

	for _, g := range full.Groups {
		for _, c := range g.Components {
			if c.Name != "" {
				w.component(g.Key, c)
			}
		}
	}
	var unsourcedBloblang []string
	for _, f := range visibleBloblang(full.BloblangFunctions) {
		file := w.platforms.source(bloblangKey("function", f.Name))
		if file == "" {
			unsourcedBloblang = append(unsourcedBloblang, f.Name+"()")
		}
		w.write(filepath.Join("partials/bloblang-functions", f.Name+".adoc"), renderBloblangSpec(f, "function", bloblangSource(file)))
	}
	for _, m := range visibleBloblang(full.BloblangMethods) {
		file := w.platforms.source(bloblangKey("method", m.Name))
		if file == "" {
			unsourcedBloblang = append(unsourcedBloblang, "."+m.Name+"()")
		}
		source := bloblangSource(file)
		w.write(filepath.Join("partials/bloblang-methods", m.Name+".adoc"), renderBloblangSpec(withCategoryText(m), "method", source))
		for category, v := range categoryVariants(m) {
			w.write(filepath.Join("partials/bloblang-methods", categoryVariantName(m.Name, category)+".adoc"), renderBloblangSpec(v, "method", source))
		}
	}
	// The Cloud build only allows pure Bloblang, so its schema decides which
	// functions and methods the Cloud docs list.
	cloudRaw, err := schema.Cloud("", "").MarshalJSONV0()
	if err != nil {
		panic(err)
	}
	cloud, err := parseFullSchema(cloudRaw)
	if err != nil {
		panic(err)
	}
	if len(unsourcedBloblang) > 0 {
		// Registered in a loop or from a struct field, so the scan can't read
		// the name; their banners name the repository.
		fmt.Printf("Bloblang functions and methods whose registering file docs_gen could not read: %v\n", strings.Join(unsourcedBloblang, ", "))
	}
	w.write("partials/bloblang/functions.adoc", renderFunctionsList(full.BloblangFunctions, bloblangNames(cloud.BloblangFunctions)))
	w.write("partials/bloblang/methods.adoc", renderMethodsList(full.BloblangMethods, bloblangNames(cloud.BloblangMethods)))
	w.configObjects(raw)
	templateRaw, err := schema.Standard("", "").Environment().TemplateSchema("", "").MarshalJSONV0()
	if err != nil {
		panic(err)
	}
	w.templateFields(templateRaw)

	fmt.Printf("Wrote %v files to %v\n", w.count, root)
}

type writer struct {
	root      string
	count     int
	platforms platformSet
}

// platformFiles writes the component catalog and the cgo-only list.
func (w *writer) platformFiles(full *fullSchema) {
	catalog, err := renderCatalog(full, w.platforms, plugins.BaseInfo)
	if err != nil {
		panic(err)
	}
	w.write("partials/platforms/catalog.json", catalog)
	w.write("partials/availability/cgo_only.adoc", renderCgoOnlyList(full, w.platforms))
}

func (w *writer) write(rel, content string) {
	p := filepath.Join(w.root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		panic(err)
	}
	w.count++
}

func (w *writer) component(key string, c componentSpec) {
	typeDir := pageTypeDir(key)
	file := c.Name + ".adoc"
	source := componentSource(w.platforms.source(componentKey(key, c.Name)))

	// Every partial is always written, empty when the component has no such
	// content, so a page that includes it keeps building after upstream
	// removes the component's last field, example, Metadata section, or
	// description.
	if len(c.Config.Children) > 0 {
		w.write(filepath.Join("partials/fields", key, file),
			generatedBannerFor(source)+"\n\n== Fields\n\n"+renderFieldsSince(c.Config.Children, "", c.Version)+"\n")
	} else {
		w.write(filepath.Join("partials/fields", key, file), emptyFieldsPartialFor(source))
	}
	if examples := renderComponentExamples(c.Examples); strings.TrimSpace(examples) != "" {
		w.write(filepath.Join("partials/examples", key, file),
			generatedBannerFor(source)+"\n\n== Examples\n\n"+examples+"\n")
	} else {
		w.write(filepath.Join("partials/examples", key, file), emptyExamplesPartialFor(source))
	}
	if md := protectCodeSpans(normalizeMetadata(extractMetadata(c.Description))); md != "" {
		w.write(filepath.Join("partials/metadata", typeDir, file), metadataBannerFor(source)+"\n\n"+md+"\n")
	} else {
		w.write(filepath.Join("partials/metadata", typeDir, file), emptyMetadataPartialFor(source))
	}
	plat := w.platforms.get(key, c.Name)
	w.write(filepath.Join("partials/availability", typeDir, file), renderAvailabilityPartial(plat))
	if c.Summary != "" || c.Description != "" || c.Version != "" || c.Status != "" || c.Footnotes != "" {
		w.write(filepath.Join("partials/descriptions", typeDir, file), renderDescriptionPartial(c, typeDir, plat, w.platforms.cloudExcluded, source))
	} else {
		w.write(filepath.Join("partials/descriptions", typeDir, file), emptyDescriptionPartialFor(source))
	}
	w.snippets(key, c)
}

func bloblangNames(specs []bloblangSpec) map[string]bool {
	names := make(map[string]bool, len(specs))
	for _, s := range specs {
		names[s.Name] = true
	}
	return names
}
