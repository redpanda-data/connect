// docs_gen writes the generated reference content under docs/modules. The
// docs site merges that directory with the pages in rp-connect-docs; see
// docs/README.md.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/redpanda-data/connect/v4/public/schema"

	_ "github.com/redpanda-data/connect/v4/public/components/a2a"
	_ "github.com/redpanda-data/connect/v4/public/components/all"
)

const (
	bannerPrefix    = "// This content is autogenerated from the component specs in https://github.com/redpanda-data/connect. Do not edit manually."
	generatedBanner = bannerPrefix + " To change it, edit the component spec and run `task docs` in that repository."
	metadataBanner  = bannerPrefix + " Metadata fields come from the `== Metadata` section of the component description. To change them, edit the component spec and run `task docs` in that repository."
	descBanner      = bannerPrefix + " The summary and description come from the component spec. To change them, edit the spec and run `task docs` in that repository.\n" +
		"//\n" +
		"// Pages consume this partial in two places so both stay fresh:\n" +
		"//   header: include::...[tag=meta]  (sets :description: for search snippets and meta tags)\n" +
		"//   body:   include::...[tag=body]   (renders the summary and description)"
)

// generatedDirs are the directories under the components module that this
// tool owns. They are emptied before every run so that a component removed
// from the code also disappears from the docs.
var generatedDirs = []string{
	"partials/fields",
	"partials/examples",
	"partials/metadata",
	"partials/descriptions",
	"partials/bloblang",
	"partials/bloblang-functions",
	"partials/bloblang-methods",
	"examples/common",
	"examples/advanced",
}

var pageTypeDirs = map[string]bool{
	"inputs": true, "outputs": true, "processors": true, "caches": true, "rate_limits": true,
	"buffers": true, "metrics": true, "scanners": true, "tracers": true,
}

func main() {
	root := "./docs/modules/components"
	flag.StringVar(&root, "dir", root, "The components module directory to write docs to")
	flag.Parse()

	raw, err := schema.Standard("", "").MarshalJSONV0()
	if err != nil {
		panic(err)
	}
	full, err := parseFullSchema(raw)
	if err != nil {
		panic(err)
	}

	for _, d := range generatedDirs {
		if err := os.RemoveAll(filepath.Join(root, d)); err != nil {
			panic(err)
		}
	}

	w := writer{root: root}
	for _, g := range full.Groups {
		for _, c := range g.Components {
			if c.Name != "" {
				w.component(g.Key, c)
			}
		}
	}
	for _, f := range full.BloblangFunctions {
		if f.Name != "" {
			w.write(filepath.Join("partials/bloblang-functions", f.Name+".adoc"), renderBloblangSpec(f, "function"))
		}
	}
	for _, m := range full.BloblangMethods {
		if m.Name != "" {
			w.write(filepath.Join("partials/bloblang-methods", m.Name+".adoc"), renderBloblangSpec(m, "method"))
		}
	}
	w.write("partials/bloblang/functions.adoc", renderFunctionsList(full.BloblangFunctions))
	w.write("partials/bloblang/methods.adoc", renderMethodsList(full.BloblangMethods))

	fmt.Printf("Wrote %v files to %v\n", w.count, root)
}

type writer struct {
	root  string
	count int
}

func (w *writer) write(rel, content string) {
	p := filepath.Join(w.root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		panic(err)
	}
	w.count++
}

func (w *writer) component(key string, c componentSpec) {
	typeDir := pageTypeDir(key)
	file := c.Name + ".adoc"

	if len(c.Config.Children) > 0 {
		w.write(filepath.Join("partials/fields", key, file),
			generatedBanner+"\n\n== Fields\n\n"+renderFields(c.Config.Children, "")+"\n")
	}
	if !pageTypeDirs[typeDir] {
		return
	}
	if examples := renderComponentExamples(c.Examples); strings.TrimSpace(examples) != "" {
		w.write(filepath.Join("partials/examples", key, file),
			generatedBanner+"\n\n== Examples\n\n"+examples+"\n")
	}
	if md := normalizeMetadata(extractMetadata(c.Description)); md != "" {
		w.write(filepath.Join("partials/metadata", typeDir, file), metadataBanner+"\n\n"+md+"\n")
	}
	if c.Summary != "" || c.Description != "" || c.Version != "" {
		w.write(filepath.Join("partials/descriptions", typeDir, file), renderDescriptionPartial(c, typeDir))
	}
	base := filepath.Join(key, c.Name+".yaml")
	if c.Config.Children != nil {
		w.write(filepath.Join("examples/common", base), buildConfigYAML(key, c.Name, c.Config.Children, false))
		w.write(filepath.Join("examples/advanced", base), buildConfigYAML(key, c.Name, c.Config.Children, true))
		return
	}
	// Components whose config is a single value, a list, or an object with no
	// fields (such as resource, fallback, and drop) have no Common or Advanced
	// split, so both snippets show the same line.
	snippet := buildValueConfigYAML(key, c.Name, c.Config)
	w.write(filepath.Join("examples/common", base), snippet)
	w.write(filepath.Join("examples/advanced", base), snippet)
}

func renderDescriptionPartial(c componentSpec, typeDir string) string {
	summary := escapePlaceholderBraces(c.Summary)
	var b strings.Builder
	b.WriteString(descBanner + "\n\n// tag::meta[]\n")
	if summary != "" {
		b.WriteString(":description: " + flattenToAttributeValue(summary) + "\n")
	}
	b.WriteString("// end::meta[]\n\n// tag::body[]\n")
	if summary != "" {
		b.WriteString(summary + "\n\n")
	}
	if c.Version != "" {
		b.WriteString("ifndef::env-cloud[]\nIntroduced in version " + htmlEscaper.Replace(c.Version) + ".\nendif::[]\n\n")
	}
	b.WriteString(renderDescriptionBody(c.Description, typeDir, c.Name) + "\n// end::body[]\n")
	return b.String()
}
